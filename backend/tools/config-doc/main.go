// Command config-doc writes docs/backend/CONFIG.md: every environment variable each service reads, with its
// default and validation rule, taken from the services' Config structs so the document cannot drift from the code.
// Run through `make gen`.
package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	gateway "platform.local/backend/services/gateway/settings"
)

// services lists each service's Config type. Add a line when a service is added.
var services = map[string]any{
	"gateway": gateway.Config{},
}

type variable struct{ name, def, rules string }

func main() {
	out := os.Stdout
	if len(os.Args) > 1 {
		f, err := os.Create(filepath.Clean(os.Args[1])) //nolint:gosec // developer tool; the Makefile passes the output path
		if err != nil {
			fmt.Fprintln(os.Stderr, "config-doc:", err)
			os.Exit(1)
		}
		defer f.Close()
		out = f
	}
	write(out)
}

func write(w io.Writer) {
	fmt.Fprintln(w, "# Backend configuration")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "Generated by `make gen` from the services' `Config` structs; do not edit by hand. Every value comes from")
	fmt.Fprintln(w, "the environment. A service refuses to start when a value is missing or fails its rule.")
	names := make([]string, 0, len(services))
	for name := range services {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(w, "\n## %s\n\n| Variable | Default | Rules |\n| --- | --- | --- |\n", name)
		for _, v := range collect(reflect.TypeOf(services[name]), "") {
			fmt.Fprintf(w, "| `%s` | %s | %s |\n", v.name, code(v.def), code(v.rules))
		}
	}
}

func collect(t reflect.Type, prefix string) []variable {
	var out []variable
	for i := range t.NumField() {
		f := t.Field(i)
		if f.Type.Kind() == reflect.Struct && f.Tag.Get("env") == "" {
			out = append(out, collect(f.Type, prefix+f.Tag.Get("envPrefix"))...)
			continue
		}
		name := f.Tag.Get("env")
		if name == "" {
			continue
		}
		out = append(out, variable{name: prefix + name, def: f.Tag.Get("envDefault"), rules: f.Tag.Get("validate")})
	}
	return out
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}
